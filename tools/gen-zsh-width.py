#!/usr/bin/env python3
"""Generate the width table zsh's line editor uses, for the terminal.

termCodepointWidth (src/TerminalStream.cpp) gives each code point the
columns zsh's line editor counts for it, so that while zsh reads a command
the terminal puts characters where zsh thinks they are (mode 2027 off, see
TerminalScreen.h). macOS's /bin/zsh (5.9) does not call the C library's
wcwidth (`nm -u /bin/zsh` lists no _wcwidth): it is built with zsh's own
Unicode 9 table, Src/wcwidth9.h, through u9_wcwidth (ENABLE_UNICODE9), which
is not Unicode 16's widths and not macOS libc's either: a regional
indicator takes 2 columns (a flag 4), U+2764 HEAVY BLACK HEART 1, and the
Devanagari spacing vowel signs (U+093E..U+0940) none.

Its ranges are written by this script, between the "generated by
tools/gen-zsh-width.py" markers in that file, from wcwidth9.h, which is not
kept in the repo. Fetch it into a folder of its own, then run from the repo
root:

    curl -sSfLO https://raw.githubusercontent.com/zsh-users/zsh/zsh-5.9/Src/wcwidth9.h
    python3 -I tools/gen-zsh-width.py <folder>/wcwidth9.h [src/TerminalStream.cpp]

u9_wcwidth's rules, in wcwidth9()'s order: non-printing (-1), combining
(0), unassigned in Unicode 9 (-1), private use (1), ambiguous (1), double
width (2), emoji width (2), else 1. The tables written are the code points
it gives 0, those it gives 2, and those it gives -1 (which zsh never writes
to the terminal as they are: it shows them as <XXXX>), for which the
terminal uses its Unicode table (termCharWidth).
"""
import re
import sys

BEGIN = "// ---- generated by tools/gen-zsh-width.py: begin"
END = "// ---- generated by tools/gen-zsh-width.py: end"
TABLES = ["private", "nonprint", "combining", "doublewidth", "ambiguous",
          "emoji_width", "not_assigned"]


def read_tables(text):
    out = {}
    for name in TABLES:
        m = re.search(r"wcwidth9_%s\[\]\s*=\s*\{(.*?)\};" % name, text, re.S)
        if not m:
            sys.exit("no table wcwidth9_%s in the header" % name)
        out[name] = [(int(a, 16), int(b, 16)) for a, b in
                     re.findall(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}",
                                m.group(1))]
    return out


def widths(tables):
    w = [1] * 0x110000
    # Applied last rule first, so the earlier rules win, as in wcwidth9().
    order = [("emoji_width", 2), ("doublewidth", 2), ("ambiguous", 1), ("private", 1),
             ("not_assigned", -1), ("combining", 0), ("nonprint", -1)]
    for name, value in order:
        for a, b in tables[name]:
            for cp in range(a, min(b, 0x10FFFF) + 1):
                w[cp] = value
    w[0] = 0
    return w


def ranges(w, value):
    out, start = [], None
    for cp in range(len(w) + 1):
        hit = cp < len(w) and w[cp] == value
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def table(name, comment, rs):
    lines = ["// " + comment, "const uint32_t %s[][2] = {" % name]
    row = []
    for a, b in rs:
        row.append("{0x%04X, 0x%04X}," % (a, b))
        if len(row) == 5:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    header = open(sys.argv[1], encoding="utf-8").read()
    target = sys.argv[2] if len(sys.argv) > 2 else "src/TerminalStream.cpp"
    w = widths(read_tables(header))
    body = "\n".join([
        BEGIN,
        "// From zsh 5.9's Src/wcwidth9.h (Unicode 9.0), as u9_wcwidth reads it.",
        "// Do not edit by hand: run the script (its header says how).",
        "namespace {",
        "",
        table("kZshZeroWidth", "Combining: zsh counts no columns.", ranges(w, 0)),
        "",
        table("kZshWide", "Double width and emoji width: two columns.", ranges(w, 2)),
        "",
        table("kZshNoWidth", "Non-printing or unassigned: zsh shows them as <XXXX>.",
              ranges(w, -1)),
        "",
        "}  // namespace",
        END,
    ])
    src = open(target, encoding="utf-8").read()
    i, j = src.find(BEGIN), src.find(END)
    if i < 0 or j < 0:
        sys.exit("markers not found in " + target)
    src = src[:i] + body + src[j + len(END):]
    open(target, "w", encoding="utf-8").write(src)


if __name__ == "__main__":
    main()
