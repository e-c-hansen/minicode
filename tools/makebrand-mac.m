        NSString *fav = [out stringByAppendingPathComponent:@"favicon"], *rd = [out stringByAppendingPathComponent:@"readme"];
        NSString *so = [out stringByAppendingPathComponent:@"social"];
        mkdirs(fav); mkdirs(rd); mkdirs(so);

        int ico[] = {16, 32, 48};
        writeICO([fav stringByAppendingPathComponent:@"favicon.ico"], ico, 3);
        writeString([NSString stringWithFormat:@"<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 64 64\" width=\"64\" height=\"64\">\n<title>mutible</title>\n%@</svg>\n",
            svgIcon(CGRectMake(0, 0, 64, 64), 64, YES, YES, @"f")], [fav stringByAppendingPathComponent:@"favicon.svg"]);
        CGContextRef t = newContext(180, 180);
        drawIconIn(t, 180, CGRectMake(0, 0, 180, 180), NO, NO);
        writeContextPNG(t, [fav stringByAppendingPathComponent:@"apple-touch-icon.png"]); CGContextRelease(t);

        for (int dark = 0; dark < 2; dark++) {
            CGContextRef hc = newContext(HDR_W * 2, HDR_H * 2);   // transparent ground
            drawHeader(hc, 2, dark);
            writeContextPNG(hc, [rd stringByAppendingPathComponent:dark ? @"mutible-header-dark@2x.png" : @"mutible-header-light@2x.png"]);
            CGContextRelease(hc);
        }
        writeString(headerSVG(), [rd stringByAppendingPathComponent:@"mutible-header.svg"]);

        CGContextRef sc = newContext(1280, 640); drawSocial(sc);
        writeContextPNG(sc, [so stringByAppendingPathComponent:@"mutible-social-1280x640.png"]); CGContextRelease(sc);

        int lin[] = {32, 64, 128, 256, 512};
        for (int i = 0; i < 5; i++) {
            NSString *d = [out stringByAppendingFormat:@"/linux/icons/%dx%d", lin[i], lin[i]];
            mkdirs(d);
            writeIcon(lin[i], [d stringByAppendingPathComponent:@"ai.ible.Mutible.png"]);
        }
        writeString([NSString stringWithFormat:@"<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 1024 1024\" width=\"1024\" height=\"1024\">\n<title>mutible</title>\n%@</svg>\n",
            svgIcon(CGRectMake(100, 100, 824, 824), 1024, YES, YES, @"a")], [out stringByAppendingPathComponent:@"icon.svg"]);
        writeSheet([out stringByAppendingPathComponent:@"sheet.png"]);
    }
    return 0;
