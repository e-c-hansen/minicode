// ---- favicon.ico: PNG frames in an ICO container ---------------------------
static NSData *pngOf(CGContextRef c) {
    CGImageRef im = CGBitmapContextCreateImage(c);
    NSBitmapImageRep *rep = [[NSBitmapImageRep alloc] initWithCGImage:im];
    NSData *d = [rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
    CGImageRelease(im);
    return d;
}
static NSData *iconPNG(int S) {
    CGContextRef c = newContext(S, S); drawIcon(c, S);
    NSData *d = pngOf(c); CGContextRelease(c);
    return d;
}
static void writeICO(NSString *path, int *sizes, int n) {
    NSMutableData *out = [NSMutableData data];
    uint16_t head[3] = { 0, 1, (uint16_t)n };
    [out appendBytes:head length:6];
    NSMutableArray *frames = [NSMutableArray array];
    for (int i = 0; i < n; i++) [frames addObject:iconPNG(sizes[i])];
    uint32_t offset = 6 + 16 * n;
    for (int i = 0; i < n; i++) {
        NSData *f = frames[i];
        uint8_t e[16] = { (uint8_t)(sizes[i] >= 256 ? 0 : sizes[i]), (uint8_t)(sizes[i] >= 256 ? 0 : sizes[i]), 0, 0, 1, 0, 32, 0 };
        uint32_t len = (uint32_t)f.length;
        memcpy(e + 8, &len, 4); memcpy(e + 12, &offset, 4);   // little-endian on every Mac
        [out appendBytes:e length:16];
        offset += len;
    }
    for (NSData *f in frames) [out appendData:f];
    [out writeToFile:path atomically:YES];
}

