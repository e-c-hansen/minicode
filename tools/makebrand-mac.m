// The icon as an SVG group, for a canvas H tall (SVG's y runs down).
// `rounded`: a squircle (as a rounded rect), else a square.
static NSString *svgIcon(CGRect body, CGFloat H, BOOL rounded, BOOL hairline, NSString *idp) {
    Layout L = layoutFor(1024, body);   // the outline drawing, at any size
    CGFloat X = body.origin.x, Y = H - CGRectGetMaxY(body), Wd = body.size.width;
    CGFloat rx = rounded ? Wd * 0.2245 : 0;
    CGFloat y0 = CGRectGetMinY(body) - 4, y1 = CGRectGetMaxY(body) + 4;   // y up
    CGFloat x0 = L.splitX + L.lean * (y0 - L.splitY), x1 = L.splitX + L.lean * (y1 - L.splitY);
    CGFloat far = CGRectGetMaxX(body) + 4, near = CGRectGetMinX(body) - 4;
    NSString *inkPoly = [NSString stringWithFormat:@"M%.2f %.2f L%.2f %.2f L%.2f %.2f L%.2f %.2f Z", x0, H - y0, far, H - y0, far, H - y1, x1, H - y1];
    NSString *paperPoly = [NSString stringWithFormat:@"M%.2f %.2f L%.2f %.2f L%.2f %.2f L%.2f %.2f Z", near, H - y0, x0, H - y0, x1, H - y1, near, H - y1];
    NSString *m = [NSString stringWithFormat:@"transform=\"matrix(%.5f 0 0 %.5f %.2f %.2f)\" d=\"%@\"", L.s, -L.s, L.ox, H - L.base, svgD(M_DISPLAY)];
    // The hyphen: a leaning parallelogram, its corners rounded by a round-joined stroke.
    CGFloat k = L.hh * 0.15, sl = L.hh * LEAN, hb = H - L.hy;
    NSString *(^hyphen)(const char *) = ^NSString *(const char *fill) {
        return [NSString stringWithFormat:@"<path fill=\"%s\" stroke=\"%s\" stroke-width=\"%.2f\" stroke-linejoin=\"round\" d=\"M%.2f %.2f L%.2f %.2f L%.2f %.2f L%.2f %.2f Z\"/>",
            fill, fill, 2 * k, L.hx + k, hb - k, L.hx + L.hw - k, hb - k, L.hx + L.hw + sl - k, hb - L.hh + k, L.hx + sl + k, hb - L.hh + k];
    };
    NSMutableString *s = [NSMutableString string];
    [s appendFormat:@"<defs><clipPath id=\"%@b\"><rect x=\"%.2f\" y=\"%.2f\" width=\"%.2f\" height=\"%.2f\" rx=\"%.2f\"/></clipPath>"
        "<clipPath id=\"%@p\"><path d=\"%@\"/></clipPath><clipPath id=\"%@i\"><path d=\"%@\"/></clipPath></defs>\n",
        idp, X, Y, Wd, Wd, rx, idp, paperPoly, idp, inkPoly];
    [s appendFormat:@"<g clip-path=\"url(#%@b)\">\n<rect x=\"%.2f\" y=\"%.2f\" width=\"%.2f\" height=\"%.2f\" fill=\"#f8fafc\"/>\n<path fill=\"#0f172a\" d=\"%@\"/>\n", idp, X, Y, Wd, Wd, inkPoly];
    [s appendFormat:@"<g clip-path=\"url(#%@p)\"><path fill=\"#0f172a\" %@/>%@</g>\n", idp, m, hyphen("#6366f1")];
    [s appendFormat:@"<g clip-path=\"url(#%@i)\"><path fill=\"#f8fafc\" %@/>%@</g>\n</g>\n", idp, m, hyphen("#818cf8")];
    if (hairline)
        [s appendFormat:@"<rect x=\"%.2f\" y=\"%.2f\" width=\"%.2f\" height=\"%.2f\" rx=\"%.2f\" fill=\"none\" stroke=\"#0f172a\" stroke-opacity=\"0.12\" stroke-width=\"%.2f\"/>\n",
            X + Wd * 0.002, Y + Wd * 0.002, Wd * 0.996, Wd * 0.996, rx, Wd * 0.004];
    return s;
}

