static void label(CGContextRef c, NSString *s, CGFloat x, CGFloat yTop, CGFloat H, unsigned color) {
    NSFont *f = [NSFont systemFontOfSize:13];
    CGColorRef col = CGColorCreateGenericRGB(((color >> 16) & 255) / 255.0, ((color >> 8) & 255) / 255.0, (color & 255) / 255.0, 1);
    NSDictionary *attrs = @{ (id)kCTFontAttributeName: f, (id)kCTForegroundColorAttributeName: (__bridge id)col };
    NSAttributedString *a = [[NSAttributedString alloc] initWithString:s attributes:attrs];
    CTLineRef line = CTLineCreateWithAttributedString((__bridge CFAttributedStringRef)a);
    CGContextSetTextPosition(c, x, H - yTop);
    CTLineDraw(line, c);
    CFRelease(line); CGColorRelease(col);
}
