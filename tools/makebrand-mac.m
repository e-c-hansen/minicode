}
// Draws a context's image at (x, yTop), scaled to w x h; `px` keeps pixels sharp.
static void put(CGContextRef c, CGContextRef src, CGFloat x, CGFloat yTop, CGFloat w, CGFloat h, CGFloat H, BOOL px) {
    CGImageRef im = CGBitmapContextCreateImage(src);
    CGContextSetInterpolationQuality(c, px ? kCGInterpolationNone : kCGInterpolationHigh);
    CGContextDrawImage(c, CGRectMake(x, H - yTop - h, w, h), im);
    CGImageRelease(im);
}
static CGContextRef iconCtx(int S) { CGContextRef c = newContext(S, S); drawIcon(c, S); return c; }

static void writeSheet(NSString *path) {
    int W = 1600, H = 1000;
    CGContextRef c = newContext(W, H);
    fillHex(c, 0xE9EDF2, 1); CGContextFillRect(c, CGRectMake(0, 0, W, H));
    fillText(c, T_WORD, 40, H - 62, 44, INK);
    label(c, @"final: m- across paper and ink", 220, 56, H, 0x475569);

    // The 1024 master on a Dock-grey ground.
    panel(c, 30, 90, 440, 460, H, 0xD5DBE3);
    CGContextRef big = iconCtx(1024); put(c, big, 50, 100, 400, 400, H, NO); CGContextRelease(big);
    label(c, @"1024 master (shown at 400)", 50, 530, H, 0x475569);

    // Every size up to 128 at actual size, on paper and on dark.
    int sizes[] = {128, 64, 48, 32, 16};
    for (int dark = 0; dark < 2; dark++) {
        CGFloat y = 90 + dark * 185;
        panel(c, 490, y, 1080, 170, H, dark ? 0x0A0A0A : 0xF8FAFC);
        CGFloat x = 520;
        for (int i = 0; i < 5; i++) {
            int S = sizes[i];
            CGContextRef ic = iconCtx(S);
            put(c, ic, x, y + 16 + (128 - S) / 2.0, S, S, H, YES);
            CGContextRelease(ic);
            label(c, [NSString stringWithFormat:@"%d", S], x, y + 160, H, dark ? 0xA3A3A3 : 0x64748B);
            x += S + 60;
        }
        // The same sizes as a Dock or a tab bar would show them beside other icons.
        label(c, dark ? @"on #0a0a0a" : @"on #f8fafc, actual size", 1420, y + 160, H, dark ? 0xA3A3A3 : 0x64748B);
    }
    // 48, 32 and 16 at 4x, nearest neighbour; the apple-touch icon.
    panel(c, 30, 570, 700, 410, H, 0xF8FAFC);
    label(c, @"48, 32, 16 at 4x (favicon.ico frames; 16 and 32 hand-tuned)", 50, 598, H, 0x475569);
    CGFloat x = 50;
    int small[] = {48, 32, 16};
    for (int i = 0; i < 3; i++) {
        CGContextRef ic = iconCtx(small[i]);
        put(c, ic, x, 615, small[i] * 4, small[i] * 4, H, YES);
        CGContextRelease(ic);
        x += small[i] * 4 + 24;
    }
    CGContextRef touch = newContext(180, 180);
    drawIconIn(touch, 180, CGRectMake(0, 0, 180, 180), NO, NO);
    put(c, touch, 520, 615, 180, 180, H, NO); CGContextRelease(touch);
    label(c, @"apple-touch-icon, 180", 520, 812, H, 0x475569);
    // A tab strip and a browser tab with the 16 px icon.
    panel(c, 50, 850, 220, 30, H, 0xE2E8F0);
    CGContextRef t16 = iconCtx(16);
    put(c, t16, 60, 857, 16, 16, H, YES);
    label(c, @"mut.ible.ai", 84, 870, H, 0x334155);
    panel(c, 50, 890, 220, 30, H, 0x1F2937);
    put(c, t16, 60, 897, 16, 16, H, YES);
    label(c, @"main.cpp", 84, 910, H, 0xE5E7EB);
    CGContextRelease(t16);

    // README headers and the social preview.
    panel(c, 750, 570, 820, 410, H, 0xD5DBE3);
    for (int dark = 0; dark < 2; dark++) {
        CGContextRef hc = newContext(HDR_W * 2, HDR_H * 2);
        fillHex(hc, dark ? 0x0D1117 : 0xFFFFFF, 1); CGContextFillRect(hc, CGRectMake(0, 0, HDR_W * 2, HDR_H * 2));
        drawHeader(hc, 2, dark);
        put(c, hc, 770, 600 + dark * 140, HDR_W, HDR_H, H, NO);
        CGContextRelease(hc);
    }
    label(c, @"README header, light and dark (1x)", 770, 885, H, 0x475569);
    CGContextRef sc = newContext(1280, 640); drawSocial(sc);
    put(c, sc, 1200, 600, 352, 176, H, NO); CGContextRelease(sc);
    label(c, @"social preview, 1280 x 640 (shown at 352)", 1200, 795, H, 0x475569);
    panel(c, 490, 460, 1080, 90, H, 0xF8FAFC);
    label(c, @"16 px: the split moves to just before the hyphen. 32 px and up: down the m's middle stem.", 510, 495, H, 0x334155);
    label(c, @"From 128 px the body sits on the macOS grid (824 of 1024, with a shadow); 64 px and below fill the square.", 510, 525, H, 0x334155);

    writeContextPNG(c, path);
    CGContextRelease(c);
}

int main(int argc, const char *argv[]) {
    @autoreleasepool {
        NSString *out = argc > 1 ? [NSString stringWithUTF8String:argv[1]] : @".";
        NSString *fav = [out stringByAppendingPathComponent:@"favicon"], *rd = [out stringByAppendingPathComponent:@"readme"];
        NSString *so = [out stringByAppendingPathComponent:@"social"];
        mkdirs(fav); mkdirs(rd); mkdirs(so);

        int ico[] = {16, 32, 48};
        writeICO([fav stringByAppendingPathComponent:@"favicon.ico"], ico, 3);
        writeString([NSString stringWithFormat:@"<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 64 64\" width=\"64\" height=\"64\">\n<title>mutible</title>\n%@</svg>\n",
            svgIcon(CGRectMake(0, 0, 64, 64), 64, YES, YES, @"f")], [fav stringByAppendingPathComponent:@"favicon.svg"]);
        CGContextRef t = newContext(180, 180);
        drawIconIn(t, 180, CGRectMake(0, 0, 180, 180), NO, NO);
        writeContextPNG(t, [fav stringByAppendingPathComponent:@"apple-touch-icon.png"]); CGContextRelease(t);

        for (int dark = 0; dark < 2; dark++) {
            CGContextRef hc = newContext(HDR_W * 2, HDR_H * 2);   // transparent ground
            drawHeader(hc, 2, dark);
            writeContextPNG(hc, [rd stringByAppendingPathComponent:dark ? @"mutible-header-dark@2x.png" : @"mutible-header-light@2x.png"]);
            CGContextRelease(hc);
        }
        writeString(headerSVG(), [rd stringByAppendingPathComponent:@"mutible-header.svg"]);

        CGContextRef sc = newContext(1280, 640); drawSocial(sc);
        writeContextPNG(sc, [so stringByAppendingPathComponent:@"mutible-social-1280x640.png"]); CGContextRelease(sc);

        int lin[] = {32, 64, 128, 256, 512};
        for (int i = 0; i < 5; i++) {
            NSString *d = [out stringByAppendingFormat:@"/linux/icons/%dx%d", lin[i], lin[i]];
            mkdirs(d);
            writeIcon(lin[i], [d stringByAppendingPathComponent:@"org.minicode.Editor.png"]);
        }
        writeString([NSString stringWithFormat:@"<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 1024 1024\" width=\"1024\" height=\"1024\">\n<title>mutible</title>\n%@</svg>\n",
            svgIcon(CGRectMake(100, 100, 824, 824), 1024, YES, YES, @"a")], [out stringByAppendingPathComponent:@"icon.svg"]);
        writeSheet([out stringByAppendingPathComponent:@"sheet.png"]);
    }
    return 0;
}
